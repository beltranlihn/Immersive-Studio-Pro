import { targets } from './cdp.mjs';
import fs from 'fs';
const wait = ms => new Promise(r => setTimeout(r, ms));
const list = await targets(9222);
const idx = list.find(t => t.type === 'page' && /index\.html/.test(t.url || ''));
const ws = new WebSocket(idx.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = () => rej(new Error('ws')); });
let _id = 0;
const send = (m, p) => new Promise((res, rej) => { const id = ++_id; const h = ev => { const x = JSON.parse(ev.data); if (x.id !== id) return; ws.removeEventListener('message', h); x.error ? rej(new Error(JSON.stringify(x.error))) : res(x.result); }; ws.addEventListener('message', h); ws.send(JSON.stringify({ id, method: m, params: p })); });
const evl = async e => (await send('Runtime.evaluate', { expression: e, returnByValue: true })).result.value;
await send('Page.enable', {});
await send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 1000, deviceScaleFactor: 1, mobile: false, screenWidth: 1600, screenHeight: 1000 });
const t = process.argv[2] || 'dome';
await evl(`(()=>{ if(!document.getElementById('landingOv'))showLanding(); _lch.ptype='${t}'; renderLauncher(); return 1; })()`);
await wait(900);
const c = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false, clip: { x: 0, y: 0, width: 1600, height: 1000, scale: 1 } });
fs.writeFileSync('scratchpad/launcher-' + t + '.png', Buffer.from(c.data, 'base64'));
console.log('scratchpad/launcher-' + t + '.png');
ws.close();
